function write(id, subject, title, lessons) {
  lessons.forEach((l, i) => (l.order = i + 1));
  const segments = Object.fromEntries([...new Set(lessons.map((l) => l.segment))].map((s) => [s, lessons.find((l) => l.segment === s).segmentTitle]));
  writeFileSync(new URL(`${id}.json`, out), JSON.stringify({ id, level: "PRE", subject, title, source, weekMode: "absolute", segments, lessons }, null, 1));
  console.log(id, lessons.length, "حصة — الأسابيع", lessons[0].unit, "→", lessons.at(-1).unit);
}

