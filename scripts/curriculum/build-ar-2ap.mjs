// ملف واحد مدموج: صفحات كل أسبوع متتالية
const parts = [];
const pagesOfWeek = new Map();
let offset = 0;
const count = (f) => Number(/Pages:\s+(\d+)/.exec(execFileSync("pdfinfo", [f]).toString())[1]);
for (const [week, rel, range] of FILES) {
  const f = join(dir, rel);
  const n = count(f);
  const [from, to] = range ?? [1, n];
  if (range) {
    // جزء من ملف: يُستخرج بـ pdfseparate ثم يُضم
    const tmp = `${merged}.w${week}-%d.pdf`;
    execFileSync("pdfseparate", ["-f", String(from), "-l", String(to), f, tmp]);
    for (let p = from; p <= to; p++) parts.push(tmp.replace("%d", String(p)));
  } else parts.push(f);
  const count_ = to - from + 1;
  pagesOfWeek.set(week, Array.from({ length: count_ }, (_, i) => offset + i + 1));
  offset += count_;
}
execFileSync("pdfunite", [...parts, merged]);

