function build(id, subject, title, source, rows) {
  const lessons = rows.map((r, i) => ({
    order: i + 1,
    segment: 1,
    segmentTitle: "السنة التحضيرية",
    unitKind: "week",
    unit: weekOf(i, rows.length),
    session: r.session,
    activity: r.activity,
    domain: r.domain,
    topic: r.topic,
    materials: r.materials,
    objectives: r.objectives,
    body: "",
    pages: r.pages,
    sample: i < 2,
  }));
  writeFileSync(new URL(`${id}.json`, out), JSON.stringify({ id, level: "PRE", subject, title, source, weekMode: "absolute", segments: { 1: "السنة التحضيرية" }, lessons }, null, 1));
  console.log(id, lessons.length, "مذكرة؛ الأسابيع", lessons.map((l) => l.unit).join(","));
}

